export function getBlockDefinition(kind: BlockKind): BlockDefinition {
  const definition = blockCatalog.find((block) => block.kind === kind)

  if (!definition) {
    throw new Error(`Unknown block kind: ${kind}`)
  }

  return definition
}

export function createBlockData(kind: BlockKind): SystemBlockData {
  const definition = getBlockDefinition(kind)

  return {
    kind: definition.canvasKind ?? definition.kind,
    label: definition.name,
    description: definition.description,
    accent: definition.accent,
    tint: definition.tint,
    metric: definition.defaultMetric,
    status: 'healthy',
    provider: definition.defaultProvider,
  }
}
